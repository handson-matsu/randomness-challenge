const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
const page=await browser.newPage({viewport:{width:1280,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{document.modelContext={registerTool(tool){window.registeredTool=tool;}}});
await page.goto('http://127.0.0.1:5173');
await page.screenshot({path:'/tmp/randomness-desktop.png',fullPage:true});
await page.locator('#choose-a').click();await page.keyboard.press('b');
assert.equal(await page.locator('#count').textContent(),'2');
await page.locator('#play .reset').click();
assert.equal(await page.locator('#count').textContent(),'0');
for(let i=0;i<100;i++)await page.keyboard.press(i%2?'b':'a');
await page.locator('#results').waitFor({state:'visible'});
assert.equal(await page.locator('.metric').count(),4);
assert.match(await page.locator('#analysis').textContent(),/99回以上/);
await page.locator('#computer').click();await page.locator('#computer').click();
assert.match(await page.locator('#computer-count').textContent(),/2回目/);
assert.equal(await page.locator('#result-sequences .tile').count(),200);
const readback=await page.evaluate(()=>window.registeredTool.execute({}));
assert.equal(await page.evaluate(()=>{try{window.registeredTool.execute({unexpected:true});return false;}catch{return true;}}),true);
assert.equal(readback.human.switches,99);assert.equal(readback.attempt,2);
await page.screenshot({path:'/tmp/randomness-results.png',fullPage:true});
await page.setViewportSize({width:375,height:812});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'/tmp/randomness-mobile-results.png',fullPage:true});
await page.locator('#results .reset').click();
await page.screenshot({path:'/tmp/randomness-mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
assert.deepEqual(errors,[]);
console.log('Browser checks passed: 100 inputs, keyboard, reset, 4 metrics, repeat computer, WebMCP readback, 375px layout, no runtime errors.');
await browser.close();
